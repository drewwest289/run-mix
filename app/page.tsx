"use client";

import { useEffect, useState } from "react";

interface RunSummary {
  id: number;
  name: string;
  startDate: string;
  distanceMeters: number;
  movingTimeSec: number;
  averageHeartrate: number | null;
  averageCadence: number | null;
}

interface Pick {
  track: {
    id: string;
    uri: string;
    name: string;
    artists: string[];
    durationMs: number;
    source: "liked" | "top";
    bpm: number | null;
  };
  lapIndex: number;
  targetSpm: number;
  matchedBpm: number;
  effort: "easy" | "moderate" | "hard";
}

function fmtDuration(sec: number) {
  const m = Math.floor(sec / 60);
  const s = Math.round(sec % 60);
  return `${m}:${s.toString().padStart(2, "0")}`;
}

function fmtDistance(meters: number) {
  return `${(meters / 1609.34).toFixed(2)} mi`;
}

const EFFORT_COLOR: Record<string, string> = {
  easy: "bg-emerald-100 text-emerald-800",
  moderate: "bg-amber-100 text-amber-800",
  hard: "bg-rose-100 text-rose-800",
};

export default function Home() {
  const [status, setStatus] = useState<{ spotify: boolean; strava: boolean } | null>(null);
  const [runs, setRuns] = useState<RunSummary[]>([]);
  const [runsError, setRunsError] = useState<string | null>(null);
  const [selectedRun, setSelectedRun] = useState<RunSummary | null>(null);
  const [generating, setGenerating] = useState(false);
  const [genError, setGenError] = useState<string | null>(null);
  const [picks, setPicks] = useState<Pick[] | null>(null);
  const [candidateInfo, setCandidateInfo] = useState<{ pool: number; withBpm: number } | null>(null);
  const [creating, setCreating] = useState(false);
  const [playlistUrl, setPlaylistUrl] = useState<string | null>(null);

  useEffect(() => {
    fetch("/api/status")
      .then((r) => r.json())
      .then(setStatus);
  }, []);

  useEffect(() => {
    if (!status?.strava) return;
    fetch("/api/runs")
      .then((r) => r.json())
      .then((data) => {
        if (data.error) setRunsError(data.error);
        else setRuns(data.runs);
      });
  }, [status?.strava]);

  async function generate(run: RunSummary) {
    setSelectedRun(run);
    setGenerating(true);
    setGenError(null);
    setPicks(null);
    setPlaylistUrl(null);
    try {
      const res = await fetch("/api/generate", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ activityId: run.id }),
      });
      const data = await res.json();
      if (data.error) throw new Error(data.error);
      setPicks(data.picks);
      setCandidateInfo({ pool: data.candidatePoolSize, withBpm: data.candidatesWithBpm });
    } catch (err) {
      setGenError(String(err));
    } finally {
      setGenerating(false);
    }
  }

  async function createPlaylist() {
    if (!picks || !selectedRun) return;
    setCreating(true);
    try {
      const res = await fetch("/api/playlist", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          name: `Run Mix — ${selectedRun.name}`,
          description: `Generated by Run Mix from ${selectedRun.name} (${fmtDistance(selectedRun.distanceMeters)})`,
          trackUris: picks.map((p) => p.track.uri),
        }),
      });
      const data = await res.json();
      if (data.error) throw new Error(data.error);
      setPlaylistUrl(data.url);
    } catch (err) {
      setGenError(String(err));
    } finally {
      setCreating(false);
    }
  }

  const bothConnected = status?.spotify && status?.strava;

  return (
    <div className="min-h-screen bg-zinc-50 text-zinc-900">
      <main className="mx-auto max-w-3xl px-6 py-10">
        <h1 className="text-2xl font-bold">Run Mix</h1>
        <p className="mt-1 text-zinc-600">
          Playlists built from your actual cadence &amp; heart rate, pulled from songs you already love.
        </p>

        <section className="mt-8 flex gap-4">
          <div className="flex-1 rounded-lg border bg-white p-4">
            <div className="flex items-center justify-between">
              <span className="font-medium">Spotify</span>
              <span className={status?.spotify ? "text-emerald-600" : "text-zinc-400"}>
                {status?.spotify ? "Connected" : "Not connected"}
              </span>
            </div>
            {!status?.spotify && (
              <a href="/api/auth/spotify" className="mt-3 inline-block rounded bg-emerald-600 px-3 py-1.5 text-sm font-medium text-white hover:bg-emerald-700">
                Connect Spotify
              </a>
            )}
          </div>
          <div className="flex-1 rounded-lg border bg-white p-4">
            <div className="flex items-center justify-between">
              <span className="font-medium">Strava</span>
              <span className={status?.strava ? "text-emerald-600" : "text-zinc-400"}>
                {status?.strava ? "Connected" : "Not connected"}
              </span>
            </div>
            {!status?.strava && (
              <a href="/api/auth/strava" className="mt-3 inline-block rounded bg-orange-600 px-3 py-1.5 text-sm font-medium text-white hover:bg-orange-700">
                Connect Strava
              </a>
            )}
          </div>
        </section>

        {bothConnected && (
          <section className="mt-8">
            <h2 className="text-lg font-semibold">Pick a run</h2>
            {runsError && <p className="mt-2 text-sm text-rose-600">{runsError}</p>}
            <div className="mt-3 divide-y rounded-lg border bg-white">
              {runs.map((run) => (
                <button
                  key={run.id}
                  onClick={() => generate(run)}
                  className={`flex w-full items-center justify-between px-4 py-3 text-left hover:bg-zinc-50 ${
                    selectedRun?.id === run.id ? "bg-zinc-100" : ""
                  }`}
                >
                  <div>
                    <div className="font-medium">{run.name}</div>
                    <div className="text-sm text-zinc-500">
                      {fmtDistance(run.distanceMeters)} · {fmtDuration(run.movingTimeSec)}
                      {run.averageHeartrate ? ` · ${Math.round(run.averageHeartrate)} bpm avg` : ""}
                      {run.averageCadence ? ` · ${Math.round(run.averageCadence * 2)} spm` : ""}
                    </div>
                  </div>
                  <span className="text-sm text-zinc-400">{new Date(run.startDate).toLocaleDateString()}</span>
                </button>
              ))}
              {runs.length === 0 && !runsError && (
                <div className="px-4 py-3 text-sm text-zinc-500">Loading runs…</div>
              )}
            </div>
          </section>
        )}

        {generating && <p className="mt-6 text-zinc-500">Matching tracks to your cadence…</p>}
        {genError && <p className="mt-6 text-sm text-rose-600">{genError}</p>}

        {picks && selectedRun && (
          <section className="mt-8">
            <div className="flex items-center justify-between">
              <h2 className="text-lg font-semibold">Mix for {selectedRun.name}</h2>
              <button
                onClick={createPlaylist}
                disabled={creating}
                className="rounded bg-emerald-600 px-4 py-2 text-sm font-medium text-white hover:bg-emerald-700 disabled:opacity-50"
              >
                {creating ? "Creating…" : "Create on Spotify"}
              </button>
            </div>
            {candidateInfo && (
              <p className="mt-1 text-sm text-zinc-500">
                Matched BPM for {candidateInfo.withBpm} of {candidateInfo.pool} candidate tracks from your library.
              </p>
            )}
            {playlistUrl && (
              <p className="mt-2 text-sm">
                Created!{" "}
                <a className="font-medium text-emerald-700 underline" href={playlistUrl} target="_blank" rel="noreferrer">
                  Open in Spotify
                </a>
              </p>
            )}
            <ol className="mt-3 divide-y rounded-lg border bg-white">
              {picks.map((p, i) => (
                <li key={`${p.track.id}-${i}`} className="flex items-center justify-between px-4 py-2.5">
                  <div>
                    <div className="font-medium">{p.track.name}</div>
                    <div className="text-sm text-zinc-500">{p.track.artists.join(", ")}</div>
                  </div>
                  <div className="flex items-center gap-2 text-right">
                    <span className={`rounded-full px-2 py-0.5 text-xs font-medium ${EFFORT_COLOR[p.effort]}`}>
                      {p.effort}
                    </span>
                    <span className="text-sm text-zinc-500">
                      {p.matchedBpm} bpm (target {Math.round(p.targetSpm)} spm)
                    </span>
                  </div>
                </li>
              ))}
            </ol>
          </section>
        )}

        <footer className="mt-12 text-xs text-zinc-400">
          Tempo data from{" "}
          <a className="underline" href="https://getsongbpm.com" target="_blank" rel="noreferrer">
            GetSongBPM
          </a>
          .
        </footer>
      </main>
    </div>
  );
}
